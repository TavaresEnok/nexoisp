package leitura

import (
	"os"
	"strings"
	"testing"

	gen "nexoisp/api-go/internal/modules/leitura/gen"
)

func TestBalanceReadQueryShape(t *testing.T) {
	source, err := os.ReadFile("queries/balance_shadow_compare.sql")
	if err != nil {
		t.Fatal(err)
	}
	sqlText := sqlWithoutLineComments(string(source))
	generated := strings.ToLower(gen.BalanceShadowCompare)
	for _, piece := range []string{
		"from invoices i",
		"left join lateral",
		"from invoice_movements mv",
		"mv.tenant_id = i.tenant_id",
		"mv.invoice_id = i.id",
		"sum(mv.nominal_delta)",
		"sum(mv.fee_delta)",
		"sum(mv.discount_delta)",
		"array_agg(mv.status_after order by mv.id desc)",
		"from payments py",
		"py.invoice_id = i.id",
		"py.tenant_id = i.tenant_id",
		"sum(py.signed_cents)",
		"where i.id = any($1::uuid[])",
		"is true as matches",
		"as residual_cents",
		"as excess_cents",
		"as collectible_cents",
		"case when x.status = 'canceled' then 0",
	} {
		if !strings.Contains(sqlText, piece) {
			t.Fatalf("sql sem %s", piece)
		}
		if !strings.Contains(generated, piece) {
			t.Fatalf("sqlc sem %s", piece)
		}
	}
	if strings.Contains(sqlText, "financial_balance_shadow") || strings.Contains(generated, "financial_balance_shadow") {
		t.Fatal("a consulta dedicada não pode ler a view")
	}
	if strings.Contains(sqlText, "group by tenant_id") || strings.Contains(generated, "group by tenant_id") {
		t.Fatal("agregado do tenant inteiro")
	}
	if strings.Contains(sqlText, "coalesce(m.nominal_cents") || strings.Contains(sqlText, "coalesce(nominal_cents, 0)") {
		t.Fatal("nominal ausente não pode virar zero")
	}
	header, err := os.ReadFile("gen/balance_shadow_compare.sql.go")
	if err != nil {
		t.Fatal(err)
	}
	head := string(header)
	if !strings.Contains(head, "Code generated by sqlc. DO NOT EDIT.") || !strings.Contains(head, "sqlc v1.31.1") || !strings.Contains(head, "source: balance_shadow_compare.sql") {
		t.Fatal("cabeçalho sqlc")
	}
}

func sqlWithoutLineComments(source string) string {
	var b strings.Builder
	for _, line := range strings.Split(source, "\n") {
		if i := strings.Index(line, "--"); i >= 0 {
			line = line[:i]
		}
		b.WriteString(strings.ToLower(line))
		b.WriteByte('\n')
	}
	return b.String()
}

